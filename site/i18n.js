/* ===== 以下是切換邏輯,請勿修改 ===== */
(function () {
  var DEFAULT_LANG = 'en';           // 預設語言
  var KEY = 'ceci-lang';
  var HTML_LANG = { en: 'en', zh: 'zh-Hant' };

  function read() {
    try { return localStorage.getItem(KEY); } catch (e) { return null; }
  }
  function write(v) {
    try { localStorage.setItem(KEY, v); } catch (e) { /* 隱私模式等情況忽略 */ }
  }

  function apply(lang) {
    var dict = window.I18N_DICT || {};

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var entry = dict[el.getAttribute('data-i18n')];
      if (!entry) return;
      var v = entry[lang];
      if (v === undefined || v === null || v === '') v = entry.en;   // 缺翻譯就退回英文
      el.textContent = v;
    });

    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var entry = dict[el.getAttribute('data-i18n-html')];
      if (!entry) return;
      var v = entry[lang];
      if (v === undefined || v === null || v === '') v = entry.en;
      el.innerHTML = v;
    });

    document.documentElement.setAttribute('lang', HTML_LANG[lang] || lang);

    document.querySelectorAll('.lang-btn').forEach(function (b) {
      var on = b.getAttribute('data-lang') === lang;
      b.classList.toggle('is-on', on);
      b.setAttribute('aria-pressed', on ? 'true' : 'false');
    });

    write(lang);
    window.CURRENT_LANG = lang;
  }

  function init() {
    var saved = read();
    apply(saved === 'zh' || saved === 'en' ? saved : DEFAULT_LANG);

    document.querySelectorAll('.lang-btn').forEach(function (b) {
      b.addEventListener('click', function () {
        apply(b.getAttribute('data-lang'));
      });
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
